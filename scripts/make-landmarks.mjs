// make-landmarks.mjs - write src/data/landmarks.json: named places around the plot with driving times.
// Places: OpenStreetMap via Overpass. Driving time and distance: OSRM public router (car profile, no traffic).
// Re-run after the plot's lat/lng in src/data/site.json changes:  node scripts/make-landmarks.mjs
import fs from 'node:fs/promises';
import path from 'node:path';

const SITE = path.resolve(import.meta.dirname, '..');
const site = JSON.parse(await fs.readFile(path.join(SITE, 'src', 'data', 'site.json'), 'utf8'));
const { lat, lng } = site.location;
const PER_CAT = 4;

const a = (r) => `(around:${r},${lat},${lng})`;
// small separate queries: public Overpass servers reject or time out on one big one
const QUERIES = [
  `nwr${a(15000)}["amenity"="hospital"]["name"];`,
  `nwr${a(15000)}["amenity"~"^(university|college)$"]["name"];`,
  `nwr${a(10000)}["amenity"="school"]["name"]["name"~"International|Academy|British|American|Indian",i];`,
  `nwr${a(15000)}["tourism"~"^(attraction|museum|theme_park)$"]["name"];`,
  `nwr${a(15000)}["shop"="mall"]["name"];`,
  `nwr${a(60000)}["aeroway"="aerodrome"]["iata"];`,
];
const HOSTS = ['https://overpass-api.de', 'https://overpass.private.coffee', 'https://overpass.kumi.systems', 'https://maps.mail.ru/osm/tools/overpass'];
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function overpassOne(q) {
  const body = 'data=' + encodeURIComponent(`[out:json][timeout:90];(${q});out center 60;`);
  for (let attempt = 0; attempt < 5; attempt++) {
    for (const host of HOSTS) {
      try {
        const r = await fetch(`${host}/api/interpreter`, {
          method: 'POST', body,
          headers: { 'User-Agent': 'resort-sales-site/0.1 (build script)', 'Content-Type': 'application/x-www-form-urlencoded', Accept: 'application/json' },
          signal: AbortSignal.timeout(120000),
        });
        if (r.ok) {
          const j = await r.json();
          // an overloaded server answers 200 with no elements and a "runtime error" remark: that is a failure, not "nothing nearby"
          if (!/error/i.test(j.remark ?? '')) return j.elements;
          console.warn(' ', host, j.remark.slice(0, 80));
          continue;
        }
        console.warn(' ', host, r.status);
      } catch (e) { console.warn(' ', host, e.cause?.code ?? e.message); }
    }
    await sleep(5000 * (attempt + 1));
  }
  throw new Error(`Overpass failed for: ${q}`);
}

async function overpass() {
  const out = [];
  for (const q of QUERIES) {
    const els = await overpassOne(q);
    console.log(els.length, 'from', q.slice(0, 70));
    out.push(...els);
    await sleep(1500);
  }
  return out;
}

const catOf = (t) =>
  t.aeroway ? 'transport'
  : t.amenity === 'hospital' ? 'health'
  : t.amenity ? 'education'
  : 'landmarks';

const dist2 = (p) => (p.lat - lat) ** 2 + ((p.lng - lng) * Math.cos((lat * Math.PI) / 180)) ** 2;

const seen = new Set();
const all = [];
for (const e of await overpass()) {
  const t = e.tags;
  const en = t['name:en'] || t.name;
  const ar = t['name:ar'] || t.name;
  const plat = e.lat ?? e.center?.lat, plng = e.lon ?? e.center?.lon;
  if (!en || plat == null || plng == null || seen.has(en)) continue;
  seen.add(en);
  all.push({ id: `osm-${e.type}-${e.id}`, cat: catOf(t), name: { en, ar }, lat: +plat.toFixed(6), lng: +plng.toFixed(6) });
}
const places = ['landmarks', 'transport', 'education', 'health']
  .flatMap((c) => all.filter((p) => p.cat === c).sort((x, y) => dist2(x) - dist2(y)).slice(0, PER_CAT));

// one OSRM table call: source 0 = the plot, destinations = every place
const coords = [[lng, lat], ...places.map((p) => [p.lng, p.lat])].map((c) => c.join(',')).join(';');
const r = await fetch(`https://router.project-osrm.org/table/v1/driving/${coords}?sources=0&annotations=duration,distance`,
  { headers: { 'User-Agent': 'resort-sales-site/0.1' }, signal: AbortSignal.timeout(60000) });
const table = await r.json();
if (table.code !== 'Ok') throw new Error(`OSRM: ${table.code} ${table.message ?? ''}`);
places.forEach((p, i) => {
  const s = table.durations[0][i + 1], m = table.distances[0][i + 1];
  p.minutes = s == null ? null : Math.max(1, Math.round(s / 60));
  p.km = m == null ? null : +(m / 1000).toFixed(1);
});

const out = {
  _comment: 'Generated by scripts/make-landmarks.mjs. Do not edit by hand; re-run the script.',
  source: {
    places: 'OpenStreetMap contributors (Overpass API)',
    times: 'OSRM public router, car profile, free-flow (no traffic)',
    from: { lat, lng, placeholder: !!site.location.placeholder },
    date: new Date().toISOString().slice(0, 10),
  },
  places,
};
await fs.writeFile(path.join(SITE, 'src', 'data', 'landmarks.json'), JSON.stringify(out, null, 2) + '\n');
for (const p of places) console.log(p.cat.padEnd(10), String(p.minutes).padStart(3), 'min', String(p.km).padStart(5), 'km ', p.name.en);
